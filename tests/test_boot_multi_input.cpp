// Deterministic test-vector generator -- NOT cryptographic randomness,
// never passed to any gpufhe:: function. Produces a smooth, bounded,
// reproducible-given-its-seed complex signal, same SHAPE as
// test_boot.cpp's own hardcoded message but with per-case amplitude/
// phase/frequency jitter so distinct cases are not trivial rescalings
// of each other.
static std::vector<cd> makeDriverMessage(uint32_t S, uint64_t messageSeed){
    std::mt19937_64 msgRng(messageSeed);
    std::uniform_real_distribution<double> ampDist(0.15,0.40);
    std::uniform_real_distribution<double> freqDist(0.01,0.03);
    std::uniform_real_distribution<double> phaseDist(0.0,2*M_PI);
    const double ampR=ampDist(msgRng), ampI=ampDist(msgRng);
    const double freqR=freqDist(msgRng), freqI=freqDist(msgRng);
    const double phR=phaseDist(msgRng), phI=phaseDist(msgRng);
    std::vector<cd> z(S);
    for(uint32_t i=0;i<S;++i)
        z[i]={ampR*std::sin(freqR*i+phR), ampI*std::cos(freqI*i+phI)};
    return z;
}

